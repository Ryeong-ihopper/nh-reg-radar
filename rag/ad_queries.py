"""광고 원문 → 검색 질의. (A) 원문 직접 · (B) 쟁점 질의 두 벌을 만든다.

왜 (B) 가 필요한가 — 광고문은 마케팅 문구고 규정은 법령 문어체라 어휘가 안 겹친다.
「연 최고 7.0%!」와 「금융상품의 이자율을 표시하는 경우 최고이자율과 최저이자율을
함께 적어야 한다」 사이에는 공통 단어가 거의 없다. 게다가 광고 하나에 쟁점이
열 개씩 들어 있어 통째로 벡터 하나에 넣으면 전부 뭉개진다.

그래서 광고에서 **감지된 특징마다 법령체 질의를 따로 만든다.** 실서비스에서는
생성 LLM(Gemma)이 이 일을 하지만, 파일럿에서는 규칙으로 둔다 — LLM 이 만들면
매번 달라져서 (A)/(B) 비교가 흔들리고, 무엇보다 "왜 이 질의가 나왔나"를 추적할 수
없어 결과 해석이 안 된다.

**누락 감지가 특히 중요하다.** 심의에서 걸리는 것은 대개 '쓴 것'이 아니라 '안 쓴
것'이다(실측: NC 다이노스 적금 판본 004→005 의 차이가 「만기후이율·중도해지이율」
한 줄, ELD 008→009 의 차이가 「미래수익 보장 아님」 단서). 그래서 있어야 할 문구가
없으면 그 사실 자체로 질의를 만든다.

  python rag/ad_queries.py
  python rag/ad_queries.py --out output/_rag/ad_queries.json
"""
